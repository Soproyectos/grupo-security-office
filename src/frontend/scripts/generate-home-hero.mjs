#!/usr/bin/env node
/**
 * Generates the hero banner of the storefront home (HOM-01).
 *
 * Output (deterministic, no dependencies, no network access):
 *   - public/images/home/hero-vitrina.svg  1600x500 wide banner
 *
 * The SVG is committed so the home renders without running this script.
 * Re-running it must produce byte-identical files (no dates, no randomness).
 * None of the artwork in public/images/categories/ works as a full-width hero
 * (240x240 tiles), so the banner is generated here with the same brand
 * palette and stroke language of generate-category-placeholders.mjs.
 *
 * Usage:
 *   node scripts/generate-home-hero.mjs         # write the SVG
 *   node scripts/generate-home-hero.mjs --check # only verify (no writes)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const FRONTEND_DIR = resolve(SCRIPT_DIR, '..')
const HERO_DIR = resolve(FRONTEND_DIR, 'public', 'images', 'home')
const HERO_FILE = resolve(HERO_DIR, 'hero-vitrina.svg')

const WIDTH = 1600
const HEIGHT = 500

const BRAND = {
  red: '#CE0203',
  redDark: '#AD0102',
  gray: '#484748',
  ink: '#1A1A1A',
  surface: '#FAFAFA',
}

/** Stroke glyphs on a 24x24 grid, the same geometry of the category tiles. */
const GLYPHS = {
  camera: [
    '<rect x="2" y="7.5" width="14" height="9" rx="1.5" />',
    '<path d="M16 11.2 21.5 8.4v7.2L16 12.8z" />',
  ],
  lock: [
    '<path d="M7.75 10.5V8a4.25 4.25 0 0 1 8.5 0v2.5" />',
    '<rect x="4.25" y="10.5" width="15.5" height="10" rx="1.5" />',
    '<path d="M12 14.2v2.6" />',
  ],
  sensor: [
    '<path d="M4.5 18.5h15L18 15.6V11a6 6 0 0 0-12 0v4.6z" />',
    '<path d="M10 21a2.2 2.2 0 0 0 4 0" />',
  ],
  battery: [
    '<rect x="1.5" y="7.5" width="16" height="9" rx="1" />',
    '<path d="M19 10.5h2.5v3H19z" />',
    '<path d="M11 8.75 7.5 13.25h2.75l-.5 3 3.5-4.5h-2.75z" />',
  ],
}

/**
 * Oversized, faint glyphs scattered on the right of the banner, where the copy
 * of the hero does not cover them. Positions are fixed (no randomness).
 */
const DECOR = [
  { family: 'camera', x: 1150, y: 60, scale: 11, opacity: 0.1 },
  { family: 'lock', x: 1420, y: 250, scale: 9, opacity: 0.09 },
  { family: 'sensor', x: 1180, y: 330, scale: 7, opacity: 0.08 },
  { family: 'battery', x: 1330, y: 40, scale: 6, opacity: 0.08 },
]

function renderHero() {
  return [
    '<!-- Generated by scripts/generate-home-hero.mjs. Do not edit by hand. -->',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}" role="img">`,
    '<title>Vitrina Grupo Security</title>',
    '<defs>',
    `<linearGradient id="hero-bg" x1="0" y1="0" x2="1" y2="1">`,
    `<stop offset="0" stop-color="${BRAND.gray}" />`,
    `<stop offset="0.6" stop-color="${BRAND.ink}" />`,
    `<stop offset="1" stop-color="${BRAND.ink}" />`,
    '</linearGradient>',
    '<radialGradient id="hero-glow" cx="18%" cy="30%" r="75%">',
    `<stop offset="0" stop-color="${BRAND.red}" stop-opacity="0.85" />`,
    `<stop offset="0.55" stop-color="${BRAND.redDark}" stop-opacity="0.4" />`,
    `<stop offset="1" stop-color="${BRAND.redDark}" stop-opacity="0" />`,
    '</radialGradient>',
    '</defs>',
    `<rect width="${WIDTH}" height="${HEIGHT}" fill="url(#hero-bg)" />`,
    `<rect width="${WIDTH}" height="${HEIGHT}" fill="url(#hero-glow)" />`,
    ...DECOR.flatMap(({ family, x, y, scale, opacity }) => [
      `<g transform="translate(${x} ${y}) scale(${scale}) translate(-12 -12)" fill="none" stroke="${BRAND.surface}" stroke-opacity="${opacity}" stroke-width="1.4" stroke-linecap="round" stroke-linejoin="round">`,
      ...GLYPHS[family],
      '</g>',
    ]),
    `<rect x="0" y="${HEIGHT - 6}" width="${WIDTH}" height="6" fill="${BRAND.red}" />`,
    '</svg>',
    '',
  ].join('\n')
}

function main() {
  const checkOnly = process.argv.slice(2).includes('--check')
  const svg = renderHero()

  if (checkOnly) {
    if (!existsSync(HERO_FILE) || readFileSync(HERO_FILE, 'utf8') !== svg) {
      console.error(`[gen:home-hero] ${HERO_FILE} is missing or drifted from the generator.`)
      process.exitCode = 1
      return
    }
    console.log(`[gen:home-hero] checked ${HERO_FILE.replace(FRONTEND_DIR, 'src/frontend')}`)
    return
  }

  mkdirSync(HERO_DIR, { recursive: true })
  writeFileSync(HERO_FILE, svg, 'utf8')
  console.log(`[gen:home-hero] wrote ${HERO_FILE.replace(FRONTEND_DIR, 'src/frontend')} (${WIDTH}x${HEIGHT})`)
}

main()
